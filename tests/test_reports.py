import pandas as pd

from src.reports import spending_by_workday


def test_spending_by_workday_calculation() -> None:
    """Проверяет корректность разделения трат на рабочие/выходные и расчет среднего."""
    # Создаем тестовый DataFrame
    data = {
        "Дата операции": [
            "2021-12-20 10:00:00",  # Понедельник (Рабочий)
            "2021-12-20 15:00:00",  # Понедельник (Рабочий)
            "2021-12-25 12:00:00",  # Суббота (Выходной)
        ],
        "Сумма платежа": [
            -1000.0,  # Трата в будний день
            -2000.0,  # Трата в будний день (среднее должно быть 1500)
            -500.0,  # Трата в выходной (среднее должно быть 500)
        ],
        "Категория": ["Супермаркеты", "Фастфуд", "Транспорт"],
    }
    df = pd.DataFrame(data)

    # Запускаем отчет до даты 2021-12-26 (чтобы наши даты попали в 3-месячное окно)
    result_df = spending_by_workday(df, "2021-12-26")

    assert isinstance(result_df, pd.DataFrame)
    assert len(result_df) == 2

    # Превращаем результат в словарь для удобной проверки
    res_dict = result_df.set_index("Тип дня")["Средние траты"].to_dict()

    assert res_dict["Рабочий день"] == 1500
    assert res_dict["Выходной день"] == 500
